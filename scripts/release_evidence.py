"""CI-5 — write RELEASE_EVIDENCE.md for a release run, from what the run produced.

Every line is read from the release directory and the run's own environment;
nothing is typed in. The record names the commit, the run, how each platform
was signed, the SHA-256 of every installer, the SBOM, the signed provenance and
channel index, and how an owner checks a download.

    python scripts/release_evidence.py --dir dist --version 0.9.1 --channel beta \\
        --signing require-except-macos --out dist/RELEASE_EVIDENCE.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SIGNING_WORDS = {
    "require": "Windows (Authenticode), macOS (Developer ID, notarised) and Linux (GPG) are signed.",
    "require-except-macos": (
        "Windows is Authenticode-signed with Raiker's self-signed beta certificate; Linux packages "
        "carry detached GPG signatures; macOS is built unsigned (no Apple Developer ID yet)."
    ),
    "skip": "No platform signatures: an unsigned test build.",
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def render(directory: Path, *, version: str, channel: str, signing: str, environ: dict[str, str]) -> str:
    server = environ.get("GITHUB_SERVER_URL", "https://github.com")
    repository = environ.get("GITHUB_REPOSITORY", "")
    run_id = environ.get("GITHUB_RUN_ID", "")
    commit = environ.get("GITHUB_SHA", "")
    run_url = f"{server}/{repository}/actions/runs/{run_id}" if repository and run_id else "(not run in CI)"
    identities = json.loads((ROOT / "desktop" / "signing" / "identities.json").read_text(encoding="utf-8"))
    installers = sorted(
        path for path in directory.iterdir()
        if path.is_file() and path.name.startswith("Raiker-") and path.suffix in {".exe", ".msi", ".dmg", ".zip", ".AppImage", ".deb", ".rpm"}
    )
    lines = [
        f"# Release evidence — Raiker {version} ({channel})",
        "",
        "Generated by the release workflow from this run's own outputs.",
        "",
        "| | |",
        "|---|---|",
        f"| Commit | `{commit or '(local)'}` |",
        f"| Release run | {run_url} |",
        f"| Signing | `{signing}` — {SIGNING_WORDS.get(signing, signing)} |",
        f"| Windows publisher pin | `{identities['windows']['subject']}`, thumbprint `{identities['windows']['thumbprint_sha1']}` |",
        f"| Linux key | fingerprint `{identities['linux']['fingerprint']}` |",
        "",
        "## Installers",
        "",
        "| File | SHA-256 | Manifest signature |",
        "|---|---|---|",
    ]
    for path in installers:
        signed = (directory / f"{path.name}.manifest.json.sig").is_file()
        lines.append(f"| `{path.name}` | `{_sha256(path)}` | {'yes' if signed else 'no'} |")
    extras = [
        (f"desktop-{channel}.json", "Signed update channel index"),
        (f"desktop-{channel}.json.sig", "Its Ed25519 signature"),
        (f"raiker-{version}.spdx.json", "SBOM (SPDX)"),
        ("release-public-key.txt", "Release public key"),
    ]
    lines += ["", "## Channel, SBOM and provenance", ""]
    for name, what in extras:
        present = (directory / name).is_file()
        lines.append(f"- {what}: `{name}`{'' if present else ' — **missing**'}")
    provenance = sorted(path.name for path in directory.glob("*provenance*"))
    lines.append(f"- Signed provenance: {', '.join(f'`{name}`' for name in provenance) or '**missing**'}")
    lines += [
        "",
        "## Checking a download",
        "",
        f"    gh attestation verify <file> --repo {repository or '<owner>/<repo>'}",
        "    gpg --import raiker-linux-signing-key.asc && gpg --verify <file>.asc <file>",
        "    python -m raiker.app.platform_signatures windows <file>.exe",
        "",
        "Installed Raiker checks every update against the release public key above",
        "before it changes anything.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--dir", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--channel", required=True)
    parser.add_argument("--signing", required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    text = render(args.dir, version=args.version, channel=args.channel, signing=args.signing, environ=dict(os.environ))
    args.out.write_text(text, encoding="utf-8")
    missing = text.count("**missing**")
    print(text)
    if missing:
        print(f"refused: {missing} release output(s) missing", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
